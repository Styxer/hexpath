"""Export the mini fixture as plain SQL: the Java integration tests load exactly what the pipeline produces.

CI regenerates this file and fails if it differs from the committed copy (seed drift).
"""
from __future__ import annotations

import json
from datetime import datetime, timezone
from pathlib import Path

from .db.store import release_stats, table_rows
from .model import input_hash
from .pipeline import load_dataset
from .sources import MINI_ZONES

SEED_TIME = datetime(2026, 11, 1, tzinfo=timezone.utc).isoformat()


def _lit(v) -> str:
    if v is None:
        return "NULL"
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, (int, float)):
        return repr(v)
    return "'" + str(v).replace("'", "''") + "'"


def export_seed(out: Path) -> Path:
    ds = load_dataset("fixture:mini", MINI_ZONES)
    stats = json.dumps(release_stats(ds), sort_keys=True, ensure_ascii=False)
    lines = [
        "-- Generated by `python -m geopipeline export-seed` from data/fixtures/mini. Do not edit by hand.",
        "-- Loaded by the Java integration tests as geo_writer into a freshly migrated database.",
        "INSERT INTO dataset_release (input_hash, source, source_timestamp, created_at, published_at, status, stats, report)",
        f"VALUES ({_lit(input_hash(ds))}, 'fixture:mini', {_lit(ds.source_timestamp.isoformat())}, {_lit(SEED_TIME)},"
        f" {_lit(SEED_TIME)}, 'ACTIVE', {_lit(stats)}::jsonb, '{{}}'::jsonb);",
        "DO $$ BEGIN IF (SELECT max(id) FROM dataset_release) <> 1 THEN"
        " RAISE EXCEPTION 'seed expects an empty, freshly migrated database'; END IF; END $$;",
        "SELECT hexpath_create_partitions(1);",
    ]
    for table, columns, rows in table_rows(1, ds):
        for row in rows:
            lines.append(f"INSERT INTO {table} ({', '.join(columns)}) VALUES ({', '.join(map(_lit, row))});")
    lines.append("INSERT INTO dataset_event (release_id, type, payload, created_at) VALUES"
                 f" (1, 'RELEASE_ACTIVATED', '{{\"release_id\": 1, \"previous\": null}}'::jsonb, {_lit(SEED_TIME)});")
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return out
